def cut(start_anchor, end_anchor):
    """删掉 [start_anchor, end_anchor) 之间的内容（含 start，不含 end）。"""
    global text
    a = text.find(start_anchor)
    b = text.find(end_anchor)
    assert 0 < a < b, 'cut 锚点不对'
    removed = b - a
    text = text[:a] + text[b:]
    return removed


