def after(anchor, payload, tail='\n'):
    """把 payload 插到 anchor 所在块结束后（tail 是该块收尾标志）。"""
    global text
    i = text.find(anchor)
    assert i > 0, 'anchor 没找到：' + anchor[:40]
    j = text.find(tail, i)
    assert j > 0, 'tail 没找到：' + anchor[:40]
    k = text.find('\n', j) + 1
    text = text[:k] + payload + text[k:]


