# ---------- A4：数据似然在读什么（接在 J(θ) 那个 math 块之后） ----------
after("tag: '【slides】平均负对数似然（代价函数）' },", r'''        { t: 'p', md: r`**$L(\\theta)$ 在读什么**：它把整个语料里**每一个** "中心词 → 上下文词" 的预测概率**连乘**起来。
连乘的含义是"这些事同时发生的可能性"。但概率都 $\le 1$，几十亿项连乘会直接下溢成 0 —— 所以取 $-\\log$ 把它变成**求和**，这就是 $J(\\theta)$ 的来历。
**最小化 $J$ ⟺ 最大化预测准确率**，这两句话说的是同一件事。` },
''', tail='` },')

