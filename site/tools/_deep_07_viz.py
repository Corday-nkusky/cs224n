def after_viz(head_anchor, payload):
    """找到 head_anchor 之后的第一个 viz 块，把说明插在它后面。"""
    global text
    h = text.find(head_anchor)
    assert h > 0, 'head 没找到：' + head_anchor[:40]
    v = text.find("{ t: 'viz'", h)
    assert v > 0, 'viz 没找到：' + head_anchor[:40]
    j = text.find('\n', v) + 1
    text = text[:j] + payload + text[j:]


def after(anchor, payload, tail='\n'):
    global text
    i = text.find(anchor)
    assert i > 0, 'anchor 没找到：' + anchor[:44]
    j = text.find(tail, i)
    assert j > 0, 'tail 没找到：' + anchor[:44]
    k = text.find('\n', j) + 1
    text = text[:k] + payload + text[k:]


